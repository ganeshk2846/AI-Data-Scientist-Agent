"""
Explicit typed contracts for the core agents:
Router, Planner, Clarification, and Visualization, plus Answerability and Repair.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field
from backend.app.agents.router import IntentType, RouteResult
from backend.app.sql.executor import QueryExecutionResult


class AbstentionType(str, Enum):
    UNSUPPORTED_DOMAIN = "unsupported_domain"
    MISSING_SCHEMA_ENTITIES = "missing_schema_entities"
    OUT_OF_TEMPORAL_SCOPE = "out_of_temporal_scope"
    AMBIGUOUS_WITHOUT_CLARIFICATION = "ambiguous_without_clarification"


class AnswerabilityAssessment(BaseModel):
    """Result of evaluating whether the question can be answered from real warehouse data."""
    is_answerable: bool
    confidence: float = Field(ge=0.0, le=1.0)
    abstention_type: Optional[AbstentionType] = None
    refusal_reason: Optional[str] = None
    available_alternatives: List[str] = Field(default_factory=list)


class ClarificationOption(BaseModel):
    option_id: str
    label: str
    description: str
    inferred_query: str


class ClarificationResponse(BaseModel):
    """Clarification request raised to the user."""
    needs_clarification: bool
    question: Optional[str] = None
    ambiguity_reason: Optional[str] = None
    options: List[ClarificationOption] = Field(default_factory=list)
    default_interpretation: Optional[str] = None


class PlanStep(BaseModel):
    """Single node in the execution DAG."""
    step_id: str
    tool_name: str
    description: str
    dependencies: List[str] = Field(default_factory=list)
    arguments: Dict[str, Any] = Field(default_factory=dict)
    status: Literal["pending", "running", "succeeded", "failed", "skipped"] = "pending"
    output: Optional[Any] = None
    error: Optional[str] = None
    duration_ms: float = 0.0


class ExecutionPlan(BaseModel):
    """Typed execution DAG generated by the Planner Agent."""
    plan_id: str
    goal: str
    steps: List[PlanStep] = Field(default_factory=list)
    current_step_id: Optional[str] = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    def get_step(self, step_id: str) -> Optional[PlanStep]:
        for s in self.steps:
            if s.step_id == step_id:
                return s
        return None


class RepairAttempt(BaseModel):
    """Details of a single SQL repair iteration."""
    attempt_number: int = Field(..., ge=1, le=2)
    original_sql: str
    error_message: str
    repaired_sql: str
    explanation: str
    success: bool
    validation_passed: bool


class ChartType(str, Enum):
    BAR = "bar"
    LINE = "line"
    SCATTER = "scatter"
    PIE = "pie"
    TABLE = "table"


class ChartSpecification(BaseModel):
    """Typed visualization specification for frontend Plotly rendering."""
    chart_type: ChartType
    title: str
    x_axis_field: Optional[str] = None
    y_axis_field: Optional[str] = None
    category_field: Optional[str] = None
    description: Optional[str] = None
    data_points_count: int = 0
    fallback_to_table: bool = False
